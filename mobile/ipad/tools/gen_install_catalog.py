#!/usr/bin/env python3
"""Writes Lastbook/Engine/Install/InstallCatalogData.swift from the desktop's published download list (manifest-v1.json):
packs, state maps and address indexes with their names, sizes, SHA-256 and installed sizes. The iPad checks a zip chosen in
Files against it, as desktop setup checks a found file. The local AI model is included (its file is on huggingface.co, as desktop).

  python3 tools/gen_install_catalog.py [../../derived/release/manifest-v1.json]
"""
import json, sys, os
from pathlib import Path

repo = Path(os.environ.get('LASTBOOK_SOURCE', Path(__file__).resolve().parents[3]))
src = Path(sys.argv[1]) if len(sys.argv) > 1 else repo / 'derived/release/manifest-v1.json'
m = json.loads(src.read_text(encoding='utf-8'))
keep = {'version': m['version'], 'published': m.get('published'),
        'packs': m.get('packs', []), 'maps': m.get('maps', []), 'address_indexes': m.get('address_indexes', []),
        'models': m.get('models', [])}
text = json.dumps(keep, indent=1, sort_keys=True, ensure_ascii=True)
assert '"""' not in text and '\\(' not in text
out = Path(__file__).resolve().parents[1] / 'Lastbook/Engine/Install/InstallCatalogData.swift'
out.write_text('// Generated by tools/gen_install_catalog.py from the desktop manifest-v1.json (published %s). Do not edit.\n'
               'enum InstallCatalogData {\n    static let json = #"""\n%s\n"""#\n}\n' % (m.get('published'), text), encoding='utf-8')
print(out, len(text), 'bytes;', len(keep['packs']), 'packs,', len(keep['maps']), 'maps,', len(keep['address_indexes']), 'address indexes,', len(keep['models']), 'models')
