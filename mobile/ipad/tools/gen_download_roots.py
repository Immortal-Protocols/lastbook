#!/usr/bin/env python3
"""Writes Lastbook/Engine/Install/DownloadRoots.swift from the desktop's engine/setup/roots.pem: the only root certificates
a download may chain to (on top of the system's own trust). Built into the app, so a missing file cannot loosen the rule.

  python3 tools/gen_download_roots.py [../../engine/setup/roots.pem]
"""
import base64, hashlib, re, sys, os
from pathlib import Path

repo = Path(os.environ.get('LASTBOOK_SOURCE', Path(__file__).resolve().parents[3]))
src = Path(sys.argv[1]) if len(sys.argv) > 1 else repo / 'engine/setup/roots.pem'
text = src.read_text(encoding='ascii')
blocks = re.findall(r'-----BEGIN CERTIFICATE-----\n(.*?)\n-----END CERTIFICATE-----', text, re.S)
ders = [''.join(b.split()) for b in blocks]
lines = []
for d in ders:
    fp = hashlib.sha256(base64.b64decode(d)).hexdigest()
    lines.append(f'        "{d}",   // sha256 {fp}')
out = Path(__file__).resolve().parents[1] / 'Lastbook/Engine/Install/DownloadRoots.swift'
out.write_text('// Generated by tools/gen_download_roots.py from the desktop engine/setup/roots.pem '
               f'(sha256 {hashlib.sha256(text.encode()).hexdigest()}). Do not edit.\n'
               'enum DownloadRoots {\n    /// DER certificates, base64.\n    static let der: [String] = [\n'
               + '\n'.join(lines) + '\n    ]\n}\n', encoding='ascii')
print(out, len(ders), 'roots')
